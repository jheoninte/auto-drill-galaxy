import assert from 'node:assert/strict';
import {createInitialState, hydrateState} from '../web-prototype/game/state.js';
import {ROUTES, isRouteUnlocked, getRouteProgress, recordRouteMining, recordRouteClear, claimRoute, equipRoute, trackRoute} from '../web-prototype/game/routes.js';
import {advanceMining, advanceCombat, applyOfflineProgress, getDerivedStats, performPrestige} from '../web-prototype/game/systems.js';
import {getPrestigeGate, getWaveConfig} from '../web-prototype/game/balance.js';
import {serializeState, parseSave} from '../web-prototype/game/storage.js';
import {CAMPAIGN} from '../web-prototype/game/campaign.js';

const state = createInitialState();
assert.equal(new Set(ROUTES.map((entry) => JSON.stringify(entry.dash))).size, ROUTES.length);
assert.equal(isRouteUnlocked(state), false);
assert.equal(claimRoute(state, 'sector-25').ok, false);
assert.equal(trackRoute(state, 'drill-mastery').ok, false);
assert.equal(equipRoute(state, 'sector-25').ok, false);
state.ship.workshop.activeModule = 'drill';
recordRouteMining(state, 30000);
assert.equal(state.prestige.routes.counters.drillOre, 0);
state.prestige.runs = 5;
assert.equal(isRouteUnlocked(state), true);
assert.equal(trackRoute(state, 'drill-mastery').ok, true);
recordRouteMining(state, NaN); recordRouteMining(state, Infinity); recordRouteMining(state, -1);
advanceMining(state, 1000);
assert.ok(state.prestige.routes.counters.drillOre > 0);
const beforeOffline = {...state.prestige.routes.counters};
state.profile.lastSeenAt = 1000;
applyOfflineProgress(state, 14_401_000);
assert.deepEqual(state.prestige.routes.counters, beforeOffline);
state.ship.workshop.activeModule = 'lance';
const drillProgress = state.prestige.routes.counters.drillOre;
recordRouteMining(state, 50000);
assert.equal(state.prestige.routes.counters.drillOre, drillProgress);
state.combat.asteroidHp = 0;
advanceCombat(state, 0, () => 0);
assert.equal(state.prestige.routes.counters.lanceKills, 1);
for (let i = 0; i < 120; i++) recordRouteClear(state, getWaveConfig(1));
assert.equal(state.prestige.routes.counters.lanceKills, 100);
assert.equal(state.prestige.routes.counters.syncBosses, 0);
state.ship.workshop.activeModule = 'sync';
recordRouteClear(state, getWaveConfig(1));
assert.equal(state.prestige.routes.counters.syncBosses, 0);
for (let i = 0; i < 30; i++) recordRouteClear(state, getWaveConfig(5));
assert.equal(state.prestige.routes.counters.syncBosses, 20);
state.ship.workshop.activeModule = 'drill';
recordRouteMining(state, 30000);
assert.equal(state.prestige.routes.counters.drillOre, 25000);
state.prestige.bestWave = 40;
state.prestige.runs = 10;
state.prestige.campaign.claimed=CAMPAIGN.map((entry) => entry.id);
const economy = () => JSON.stringify({profile:state.profile,ship:state.ship,skills:state.skills,loot:state.loot,combat:state.combat});
const beforeClaims = economy();
const stats = getDerivedStats(state);
for (const entry of ROUTES) {
  assert.equal(getRouteProgress(state, entry), entry.target);
  assert.equal(claimRoute(state, entry.id).ok, true);
  assert.equal(claimRoute(state, entry.id).ok, false);
  assert.equal(equipRoute(state, entry.id).ok, true);
  assert.deepEqual(getDerivedStats(state), stats);
}
assert.equal(economy(), beforeClaims);
assert.equal(claimRoute(state, 'bad').ok, false);
assert.equal(equipRoute(state, 'bad').ok, false);
assert.equal(trackRoute(state, 'bad').ok, false);
assert.equal(equipRoute(state, null).ok, true);
assert.equal(equipRoute(state, 'lance-mastery').ok, true);
assert.equal(trackRoute(state, 'sync-mastery').ok, true);
const routesBeforePrestige = structuredClone(state.prestige.routes);
state.combat.wave = getPrestigeGate(state);
assert.equal(performPrestige(state).ok, true);
assert.deepEqual(state.prestige.routes, routesBeforePrestige);
const restored = parseSave(serializeState(state));
assert.deepEqual(restored.prestige.routes, routesBeforePrestige);
assert.equal(claimRoute(restored, 'lance-mastery').ok, false);
const legacy = hydrateState({prestige:{runs:8,bestWave:32}});
assert.equal(isRouteUnlocked(legacy), true);
assert.equal(getRouteProgress(legacy, ROUTES[0]), 25);
assert.deepEqual(legacy.prestige.routes.counters, {drillOre:0,lanceKills:0,syncBosses:0});
assert.deepEqual(legacy.prestige.routes.claimed, []);
const bad = hydrateState({prestige:{routes:{claimed:['sector-25','bad','sector-25'],equipped:'sector-40',tracked:'bad',counters:{drillOre:Infinity,lanceKills:1000,syncBosses:-3}}}});
assert.deepEqual(bad.prestige.routes, {claimed:['sector-25'],equipped:null,tracked:null,counters:{drillOre:0,lanceKills:100,syncBosses:0}});
console.log('Route checks passed: unlock, module-only progress, offline exclusion, capped counters, cosmetic-only rewards, duplicate claims, migration, prestige and backup restore.');
